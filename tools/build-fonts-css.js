#!/usr/bin/env node
/* Generates css/fonts.css from the FONTS list in js/schema.js.  Usage: node tools/build-fonts-css.js */
'use strict';
const fs = require('fs');
const path = require('path');
const { FONTS } = require('../js/schema.js');
const LATIN = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
const EXT = 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF';
const root = path.join(__dirname, '..');
const lines = ['/* Bundled fonts (SIL Open Font License 1.1) — work offline. Generated by tools/build-fonts-css.js */'];
for (const f of FONTS) {
  const subsets = f.ext ? [['latin-ext', EXT], ['latin', LATIN]] : [['latin', LATIN]];
  for (const [sub, range] of subsets) {
    const file = f.kind === 'V' ? `${f.file}-${sub}-wght-normal.woff2` : `${f.file}-${sub}-${f.kind === 'S7' ? 700 : 400}-normal.woff2`;
    if (!fs.existsSync(path.join(root, 'fonts', file))) { console.error('missing', file); process.exitCode = 1; continue; }
    // Single-weight fonts claim the whole weight range so the browser never fakes bold.
    const weight = f.kind === 'V' ? f.weights : '100 900';
    lines.push(`@font-face{font-family:'L ${f.family}';font-style:normal;font-display:swap;font-weight:${weight};src:url('../fonts/${file}') format('woff2');unicode-range:${range}}`);
  }
}
fs.writeFileSync(path.join(root, 'css', 'fonts.css'), lines.join('\n') + '\n');
console.log(`fonts.css: ${lines.length - 1} faces`);
